// Generates src/content.generated.ts from src/guide.md, src/visualize-skill.md and every skills/*.md file.
// The MCP `guide` tool, the server instructions and the skills installed by `Blueprint --connect` all read this one
// generated module, so their text cannot drift. Writes only inside this repository.
import fs from "node:fs"; import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export function loadContent() {
  const guide = fs.readFileSync(path.join(root, "src/guide.md"), "utf8");
  const visualizeHead = fs.readFileSync(path.join(root, "src/visualize-skill.md"), "utf8");
  const dir = path.join(root, "skills");
  const skip = new Set(["ATTRIBUTION.md", "README.md", "THIRD_PARTY_NOTICES.md", "LICENSE.md"]);
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".md") && !skip.has(f)).sort() : [];
  const skills = [];
  for (const f of files) {
    const raw = fs.readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n");
    const m = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(raw);
    if (!m) { console.warn(`skills/${f}: no frontmatter; skipped`); continue; }
    const fm = Object.fromEntries(m[1].split("\n").map((l) => /^([A-Za-z_-]+):\s*(.*)$/.exec(l)).filter(Boolean).map((x) => [x[1], x[2].trim()]));
    const name = fm.name || f.slice(0, -3);
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) { console.warn(`skills/${f}: invalid name '${name}'; skipped`); continue; }
    if (!fm.description) { console.warn(`skills/${f}: no description; skipped`); continue; }
    skills.push({ name, topic: name.replace(/^blueprint-/, ""), description: fm.description, body: m[2].trim() + "\n", raw });
  }
  return { guide, visualizeHead, skills };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const c = loadContent();
  const out = `// GENERATED by scripts/build.mjs from src/guide.md, src/visualize-skill.md and skills/*.md. Do not edit.\n` +
    `export const GUIDE: string = ${JSON.stringify(c.guide)};\n` +
    `export const VISUALIZE_HEAD: string = ${JSON.stringify(c.visualizeHead)};\n` +
    `export interface BundledSkill { name: string; topic: string; description: string; body: string; raw: string }\n` +
    `export const SKILLS: BundledSkill[] = ${JSON.stringify(c.skills, null, 1)};\n`;
  fs.writeFileSync(path.join(root, "src/content.generated.ts"), out);
  console.log(`generated content: guide + ${c.skills.length} skill topic(s): ${c.skills.map((s) => s.topic).join(", ") || "(none)"}`);
}
